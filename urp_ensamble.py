from sklearn.metrics import average_precision_score

def per_term_weighted_ensemble(mlp_preds, xgb_preds, y_true, tune_idx, eval_idx):
    """Learn per-term weights on tune split, apply to eval split."""
    mlp_t, xgb_t, y_t = mlp_preds[tune_idx], xgb_preds[tune_idx], y_true[tune_idx]
    weights = np.full(y_true.shape[1], 0.5)  # default 50/50
    for j in range(y_true.shape[1]):
        if y_t[:, j].sum() < 2:  # not enough positives to score
            continue
        ap_mlp = average_precision_score(y_t[:, j], mlp_t[:, j])
        ap_xgb = average_precision_score(y_t[:, j], xgb_t[:, j])
        total = ap_mlp + ap_xgb
        if total > 0:
            weights[j] = ap_mlp / total
    blended = weights * mlp_preds[eval_idx] + (1 - weights) * xgb_preds[eval_idx]
    return blended, weights

def compute_fmax(y_true, y_pred, indices=None):
    if indices is not None:
        y_true, y_pred = y_true[:, indices], y_pred[:, indices]
    has_label = y_true.sum(axis=1) > 0
    y_true, y_pred = y_true[has_label], y_pred[has_label]
    if len(y_true) == 0:
        return 0.0, 0.0
    best_f1, best_t = 0, 0
    for t in np.arange(0.01, 1.0, 0.02):
        pred_bin = (y_pred >= t).astype(float)
        if pred_bin.sum() == 0:
            continue
        tp = (pred_bin * y_true).sum(axis=1)
        n_pred = pred_bin.sum(axis=1)
        has_pred = n_pred > 0
        if has_pred.sum() == 0:
            continue
        prec = (tp[has_pred] / n_pred[has_pred]).mean()
        rec = (tp / y_true.sum(axis=1)).mean()
        f1 = 2 * prec * rec / (prec + rec) if (prec + rec) > 0 else 0
        if f1 > best_f1:
            best_f1, best_t = f1, t
    return best_f1, best_t

