# 3-way stacking: combine ESM-2, ProtT5, and Concat ensembles
# Weights tuned per-term on tune_idx, scored on eval_idx (same split as before)

def three_way_weighted(preds_list, y_true, tune_idx, eval_idx):
    """Per-term weighted average of N prediction matrices."""
    n_terms = y_true.shape[1]
    weights = np.full((len(preds_list), n_terms), 1.0 / len(preds_list))
    y_t = y_true[tune_idx]
    for j in range(n_terms):
        if y_t[:, j].sum() < 2:
            continue
        aps = []
        for p in preds_list:
            aps.append(average_precision_score(y_t[:, j], p[tune_idx][:, j]))
        total = sum(aps)
        if total > 0:
            for k in range(len(preds_list)):
                weights[k, j] = aps[k] / total
    blended = np.zeros_like(preds_list[0][eval_idx])
    for k, p in enumerate(preds_list):
        blended += weights[k] * p[eval_idx]
    return blended, weights

# First, get the per-embedding weighted ensembles applied to FULL val
# (so we can stack them — we need them as full arrays, not just eval slice)
def per_term_full(mlp_p, xgb_p, y_true, tune_idx):
    y_t = y_true[tune_idx]
    weights = np.full(y_true.shape[1], 0.5)
    for j in range(y_true.shape[1]):
        if y_t[:, j].sum() < 2:
            continue
        ap_m = average_precision_score(y_t[:, j], mlp_p[tune_idx][:, j])
        ap_x = average_precision_score(y_t[:, j], xgb_p[tune_idx][:, j])
        if ap_m + ap_x > 0:
            weights[j] = ap_m / (ap_m + ap_x)
    return weights * mlp_p + (1 - weights) * xgb_p

