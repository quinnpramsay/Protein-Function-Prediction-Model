# xgboost_model.py
# trains one xgboost model per GO term using pre-filtered esm2 embeddings

import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from xgboost import XGBClassifier
from tqdm import tqdm
import pickle

from google.colab import drive
drive.mount('/content/drive')

# all filtered files are in the Train/ folder
DATA_DIR = "/content/drive/MyDrive/Senior Year/Undergraduate Research Program/cafa-6-protein-function-prediction/Train"

# load pre-filtered embeddings and protein ids
print("Loading data...")
embeddings = np.load(f"{DATA_DIR}/filtered_esm2.npy")
protein_ids = np.load(f"{DATA_DIR}/filtered_protein_ids.npy", allow_pickle=True).tolist()
filtered_terms = pd.read_csv(f"{DATA_DIR}/filtered_terms.tsv", sep="\t")

print(f"Embeddings: {embeddings.shape}")
print(f"Proteins: {len(protein_ids)}")
print(f"Term rows: {len(filtered_terms)}")

# get the list of unique GO terms (these become the columns of the label matrix)
frequent_terms = filtered_terms["term"].unique().tolist()
print(f"GO terms: {len(frequent_terms)}")

# build aspect mapping so we can evaluate BP, MF, CC separately later
term_aspect_map = filtered_terms.drop_duplicates("term").set_index("term")["aspect"]
term_aspects = [term_aspect_map[t] for t in frequent_terms]

# build binary label matrix
# rows = proteins (same order as embeddings), columns = GO terms
# 1 means that protein has that annotation
print("Building label matrix...")
term_to_col = {t: i for i, t in enumerate(frequent_terms)}
pid_to_row = {p: i for i, p in enumerate(protein_ids)}
labels = np.zeros((len(protein_ids), len(frequent_terms)), dtype=np.float32)

for _, row in filtered_terms.iterrows():
    if row["EntryID"] in pid_to_row and row["term"] in term_to_col:
        labels[pid_to_row[row["EntryID"]], term_to_col[row["term"]]] = 1.0

print(f"Label matrix: {labels.shape}")
print(f"Avg labels per protein: {labels.sum(axis=1).mean():.1f}")

# 90/10 train/val split
X_train, X_val, y_train, y_val = train_test_split(
    embeddings, labels, test_size=0.1, random_state=42
)
print(f"Train: {X_train.shape[0]}, Val: {X_val.shape[0]}")

# train one xgboost model per GO term
print("Training XGBoost models...")
n_terms = labels.shape[1]
models = [None] * n_terms
val_preds = np.zeros((X_val.shape[0], n_terms), dtype=np.float32)

for i in tqdm(range(n_terms), desc="XGBoost"):
    y_tr = y_train[:, i]
    y_vl = y_val[:, i]

    # skip if no positive examples exist in training split
    if y_tr.sum() == 0:
        continue

    n_neg = len(y_tr) - y_tr.sum()

    model = XGBClassifier(
        n_estimators=50,
        max_depth=4,
        learning_rate=0.3,
        scale_pos_weight=n_neg / y_tr.sum(),
        eval_metric="logloss",
        verbosity=0,
        device="cuda",
        random_state=42,
        early_stopping_rounds=5,
    )
    model.fit(X_train, y_tr, eval_set=[(X_val, y_vl)], verbose=False)
    val_preds[:, i] = model.predict_proba(X_val)[:, 1]
    models[i] = model

n_trained = sum(1 for m in models if m is not None)
print(f"Trained {n_trained}/{n_terms} models")


# fmax evaluation - sweeps thresholds and finds best protein-centric F1
def compute_fmax(y_true, y_pred, n_thresholds=51):
    thresholds = np.linspace(0.01, 0.99, n_thresholds)
    best_f1 = 0.0
    best_t = 0.0
    has_true = y_true.sum(axis=1) > 0

    for t in thresholds:
        y_bin = (y_pred >= t).astype(np.float32)
        has_pred = y_bin.sum(axis=1) > 0
        correct = (y_true * y_bin).sum(axis=1)

        if has_pred.any():
            avg_p = (correct[has_pred] / y_bin[has_pred].sum(axis=1)).mean()
        else:
            avg_p = 0.0

        if has_true.any():
            avg_r = (correct[has_true] / y_true[has_true].sum(axis=1)).mean()
        else:
            avg_r = 0.0

        if avg_p + avg_r > 0:
            f1 = 2 * avg_p * avg_r / (avg_p + avg_r)
            if f1 > best_f1:
                best_f1 = f1
                best_t = t

    return best_f1, best_t


# overall fmax
print("\nEvaluation:")
fmax, thresh = compute_fmax(y_val, val_preds)
print(f"Overall Fmax: {fmax:.4f} (threshold: {thresh:.3f})")

# per-aspect fmax (how CAFA-6 actually scores)
print("\nPer-aspect:")
term_aspects_arr = np.array(term_aspects)
aspect_fmax = {}

for aspect, code in [("BP", "P"), ("MF", "F"), ("CC", "C")]:
    mask = term_aspects_arr == code
    if mask.sum() == 0:
        continue
    fm, th = compute_fmax(y_val[:, mask], val_preds[:, mask])
    aspect_fmax[aspect] = fm
    print(f"  {aspect}: Fmax = {fm:.4f} (threshold = {th:.3f}, {mask.sum()} terms)")

cafa_score = np.mean(list(aspect_fmax.values()))
print(f"  CAFA Score: {cafa_score:.4f}")

# save models
save_path = f"{DATA_DIR}/xgboost_models_esm2.pkl"
with open(save_path, "wb") as f:
    pickle.dump(models, f)
print(f"\nSaved models to {save_path}")
print("Done!")